print("=== ЗАДАНИЕ 1. Линейный алгоритм ===")
# Считывает три целых числа и находит их среднее арифметическое (без условий и циклов)
try:
    num1 = int(input("Введите первое целое число: "))
    num2 = int(input("Введите второе целое число: "))
    num3 = int(input("Введите третье целое число: "))
    
    # Линейное вычисление среднего арифметического
    average = (num1 + num2 + num3) / 3
    print(f"Среднее арифметическое чисел {num1}, {num2} и {num3} равно: {average}")
except ValueError:
    print("Ошибка: введены не целые числа.")


print("\n=== ЗАДАНИЕ 2. Алгоритм с ветвлением ===")
# Определяет, делится ли число на 3 и на 5 одновременно
try:
    number = int(input("Введите целое число для Задания 2: "))
    
    # Проверка одновременной делимости на 3 и на 5 (или на 15)
    if number % 3 == 0 and number % 5 == 0:
        print(f"Число {number} делится на 3 и на 5 одновременно.")
    else:
        print(f"Число {number} не делится на 3 и на 5 одновременно.")
except ValueError:
    print("Ошибка: введено не целое число.")


print("\n=== ЗАДАНИЕ 3. Циклический алгоритм ===")
# Вычисляет факториал (произведение чисел от 1 до n)
try:
    n = int(input("Введите натуральное число n (n >= 1) для Задания 3: "))
    if n < 1:
        print("Ошибка: число должно быть натуральным (n >= 1).")
    else:
        product = 1
        for i in range(1, n + 1):
            product *= i
        print(f"Произведение чисел от 1 до {n} (факториал) равно: {product}")
except ValueError:
    print("Ошибка: введено не целое число.")


print("\n=== ЗАДАНИЕ 4. Комбинация условий и циклов ===")
# Выводит все чётные числа от 1 до n и подсчитывает их количество
try:
    n_even = int(input("Введите натуральное число n для Задания 4: "))
    if n_even < 1:
        print("Ошибка: число должно быть больше или равно 1.")
    else:
        even_count = 0
        print(f"Чётные числа от 1 до {n_even}:", end=" ")
        for i in range(1, n_even + 1):
            if i % 2 == 0:
                print(i, end=" ")
                even_count += 1
        print(f"\nКоличество выведенных чётных чисел: {even_count}")
except ValueError:
    print("Ошибка: введено не целое число.")