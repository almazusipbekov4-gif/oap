print("=== ЗАДАНИЕ 1. Цикл с предусловием ===")
# Считывает целое число и повторяет ввод, пока число не станет положительным
num1 = int(input("Введите число для Задания 1: "))
while num1 <= 0:
    print("Ошибка: число должно быть положительным.")
    num1 = int(input("Повторите ввод: "))
print(f"Успешно! Введено положительное число: {num1}")


print("\n=== ЗАДАНИЕ 2. Цикл с постусловием (имитация) ===")
# Запрашивает число (минимум 1 ввод), завершается при вводе числа больше 100
while True:
    num2 = int(input("Введите число для Задания 2 (больше 100 для выхода): "))
    if num2 > 100:
        print(f"Число {num2} больше 100. Выход из цикла.")
        break
    print("Число не превышает 100, повторите ввод.")


print("\n=== ЗАДАНИЕ 3. Цикл со счётчиком ===")
# Вычисляет сумму всех целых чисел от 1 до n
n = int(input("Введите целое число n (n >= 1) для Задания 3: "))
total_sum = 0
for i in range(1, n + 1):
    total_sum += i
print(f"Сумма чисел от 1 до {n} равна: {total_sum}")


print("\n=== ЗАДАНИЕ 4. Вложенные циклы ===")
# Выводит таблицу умножения от 1 до 5
print("Таблица умножения от 1 до 5:")
for i in range(1, 6):
    for j in range(1, 6):
        print(f"{i * j:4}", end="")
    print()


print("\n=== ЗАДАНИЕ 5. Анализ корректности цикла ===")
print("Исходный фрагмент кода:")
print("i = 1\nwhile i <= 10:\n    print(i)")
print("\nРезультат анализа:")
print("- Ошибка заключается в отсутствии изменения управляющей переменной i внутри цикла.")
print("- Это приведёт к бесконечному зацикливанию программы и непрерывному выводу единицы.")

print("\nИсправленный вариант кода:")
i = 1
while i <= 10:
    print(i, end=" ")
    i += 1  # Увеличение счетчика для корректного выхода из цикла
print("\nЦикл успешно отработал с изменением управляющей переменной.")