print("--- Задание 1. Простое условие ---")
# Считывает целое число и определяет, является ли оно положительным
try:
    num1 = int(input("Введите целое число для Задания 1: "))
    if num1 > 0:
        print(f"Число {num1} является положительным.")
    else:
        print(f"Число {num1} не является положительным.")
except ValueError:
    print("Ошибка: введено не целое число.")

print("\n--- Задание 2. Условие с альтернативой ---")
# Считывает целое число и определяет, чётное оно или нечётное
try:
    num2 = int(input("Введите целое число для Задания 2: "))
    if num2 % 2 == 0:
        print(f"Число {num2} — чётное.")
    else:
        print(f"Число {num2} — нечётное.")
except ValueError:
    print("Ошибка: введено не целое число.")

print("\n--- Задание 3. Множественный выбор ---")
# Считывает целое число от 1 до 100 и определяет оценку
try:
    score = int(input("Введите балл от 1 до 100 для Задания 3: "))
    if 1 <= score <= 100:
        if score >= 90:
            print("Оценка: «A»")
        elif score >= 75:
            print("Оценка: «B»")
        elif score >= 60:
            print("Оценка: «C»")
        else:
            print("Оценка: «D»")
    else:
        print("Ошибка: число вне диапазона от 1 до 100.")
except ValueError:
    print("Ошибка: введено не целое число.")

print("\n--- Задание 4. Логические операции ---")
# Определяет право на льготный тариф (возраст < 18 или наличие студенческого)
try:
    age = int(input("Введите ваш возраст для Задания 4: "))
    has_student_ticket_input = input("Есть ли студенческий билет? (да/нет): ").strip().lower()
    
    # Превращаем ввод в булево значение (True/False)
    has_student = has_student_ticket_input in ["да", "yes", "д", "y"]

    if age < 18 or has_student:
        print("Результат: Пользователь имеет право на льготный тариф.")
    else:
        print("Результат: Пользователь не имеет права на льготный тариф.")
except ValueError:
    print("Ошибка: некорректный ввод возраста.")

print("\n--- Задание 5. Вложенные условия ---")
# Считывает два целых числа и определяет большее или их равенство
try:
    a = int(input("Введите первое число для Задания 5: "))
    b = int(input("Введите второе число для Задания 5: "))

    # Использование вложенных условных конструкций
    if a != b:
        if a > b:
            print(f"Первое число ({a}) больше второго ({b}).")
        else:
            print(f"Второе число ({b}) больше первого ({a}).")
    else:
        print("Числа равны между собой.")
except ValueError:
    print("Ошибка: введены не целые числа.")